"""
Generates src/STH2005ShapeKeys.h: one STH2005::CollisionKey for every .CCL entry of every One Ver 0.60 archive of the Shadow disc.

Run from anywhere:  python3 tools/genCCLKeys.py
Inputs: build/Disks/Shadow2005.iso (read through tools/dumpCCL.py). Nothing is written but src/STH2005ShapeKeys.h.

A key is named CCLShapes_<archive path without .one, / as _>_<entry without .CCL>; the archive is part of the identity because
stage archives repeat entries (e.g. A20000ELEVATOR.CCL in several stages). Every entry must follow the layout checked by
dumpCCL.parse_ccl, otherwise the script stops. The object each entry belongs to is not recorded anywhere; the names are the entries' own.
"""
import os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dumpCCL

OUT = dumpCCL.ROOT + "src/STH2005ShapeKeys.h"


def main():
    out = [
        "#pragma once",
        '#include "STH2005Keys.h"',
        "",
        "/*",
        "GENERATED by tools/genCCLKeys.py, do not edit by hand (run the script again). One STH2005::CollisionKey for each .CCL entry of each",
        "\"One Ver 0.60\" archive of the Shadow disc, named CCLShapes_<archive>_<entry>. The comment gives the record count. Shadow himself has",
        "no .CCL (none in character/*.one, none named after him; the main.dol only names two stage objects' files).",
        "*/",
    ]
    names = {}
    entries = sorted(dumpCCL.ccl_entries(), key=lambda e: (e[0].lower(), e[1].lower()))
    for path, name, d in entries:
        shapes = len(dumpCCL.parse_ccl(d)["shapes"])
        ident = "CCLShapes_" + re.sub(r"\W", "_", path[:-4]) + "_" + re.sub(r"\W", "_", name[:-4])
        if ident in names:
            raise RuntimeError(f"{ident} names both {names[ident]} and {path} > {name}")
        names[ident] = f"{path} > {name}"
        out.append(f"/* {shapes} records */")
        out.append(f'inline const STH2005::CollisionKey {ident}{{{{"{path}"}}, "{name}"}};')
    open(OUT, "w").write("\n".join(out) + "\n")
    print(f"{len(entries)} keys written to {OUT}")


if __name__ == "__main__":
    main()
