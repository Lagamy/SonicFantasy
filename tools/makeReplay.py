"""
Turns a recording of tools/shadowLiveLog.py (made with --pad) into a Lua replay for Scripts/shadow/replay.lua.

    python3 tools/makeReplay.py tools/live_run.csv Scripts/shadow/replays/live_run.lua

Per recording: start = the first row's position. Per row: t (seconds from the first row), the stick as camera-relative forward and right parts, a = the jump button. Hypotheses, all printed so they can be checked:
- stick: pad_fx is right when positive, pad_fy is forward when negative (the game negates the pad's y; the sign of x is tried both ways and the one whose fit is tighter is kept);
- buttons: bit 0 of pad_buttons is A (seen once, in tools/pad_check.csv);
- the stick is the pad's float stick (pad_fx, pad_fy: (|raw| - 15) / 42 per axis, observed in tools/live_half.csv), kept analog;
- the camera's heading phi is not recorded: it is the circular median of (velocity angle - stick angle) over the rows moving faster than FIT_SPEED, in the original's own x / z axes;
- heading0, the way he faces at the start, is the angle of the velocity at the first row moving faster than START_SPEED.
"""
import csv
import math
import sys

FIT_SPEED = 100
START_SPEED = 10


def circular_median(angles):
    best, best_cost = 0.0, None
    for a in angles:
        cost = sum(abs(math.atan2(math.sin(b - a), math.cos(b - a))) for b in angles)
        if best_cost is None or cost < best_cost:
            best, best_cost = a, cost
    return best, best_cost / len(angles)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    rows = list(csv.DictReader(open(sys.argv[1])))
    if "pad_sx" not in rows[0]:
        sys.exit("no pad columns: record with --pad")
    t0 = float(rows[0]["t"])
    start = (float(rows[0]["pos_x"]), float(rows[0]["pos_y"]), float(rows[0]["pos_z"]))
    data = []
    for x in rows:
        sx, sy = float(x["pad_fx"]), float(x["pad_fy"])
        vx, vz = float(x["vel_x"]), float(x["vel_z"])
        data.append((float(x["t"]) - t0, -sy, sx, int(x["pad_buttons"], 16) & 1, math.atan2(vz, vx), math.hypot(vx, vz)))
    fits = {}
    for hand in (1, -1):
        angles = [v - math.atan2(hand * r, f) for _, f, r, _, v, speed in data if speed > FIT_SPEED and math.hypot(f, r) > 0.3]
        fits[hand] = circular_median(angles) if angles else (0.0, 0.0)
    hand = 1 if fits[1][1] <= fits[-1][1] else -1
    phi = fits[hand][0]
    heading0 = next((v for _, _, _, _, v, speed in data if speed > START_SPEED), 0.0)
    print(f"{len(data)} rows, {data[-1][0]:.2f} s; right sign {hand:+d} (mean error when fitted: +1 {math.degrees(fits[1][1]):.1f} deg, -1 {math.degrees(fits[-1][1]):.1f} deg); phi {math.degrees(phi):.1f} deg, heading0 {math.degrees(heading0):.1f} deg")
    name = sys.argv[2].rsplit("/", 1)[-1].removesuffix(".lua")
    with open(sys.argv[2], "w") as out:
        out.write(f"-- Generated by tools/makeReplay.py from {sys.argv[1]}; do not edit. See replay.lua.\n")
        out.write(f"ShadowReplays.{name} = {{start = {{{start[0]:.4f}, {start[1]:.4f}, {start[2]:.4f}}}, heading0 = {heading0:.6f}, phi = {phi:.6f}, rows = {{\n")
        for t, f, r, a, _, _ in data:
            out.write(f"\t{{{t:.4f}, {f:.4f}, {hand * r:.4f}, {a}}},\n")
        out.write("}}\n")


main()
