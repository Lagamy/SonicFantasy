"""
Generates src/SAShapeKeys.h: one SACollisionShapesKey for every SADX object collision table that the game's collision init is
called with by a literal table address (the 0x30-byte entries, see Physics::CollisionShape), in _Main.rel.

Run from anywhere:  python3 tools/genSAShapeKeys.py
Inputs: sadxDecomp/decompiled/pseudocode.c (Ghidra pseudocode of main.dol and _Main.rel, see tools/decomp/sadx/run.sh) and
sadxDecomp/rel/_Main.img + _Main.layout (the relocated module and its sections, see tools/decomp/sadx/buildRelImage.py).
Nothing is written but src/SAShapeKeys.h. Only _Main.rel is imported there; the other modules have no keys until they are.

Everything here is external/hypothesis: the pseudocode has no names, so a table is named after its module and RAM address (the module is
mapped at 0x80400000 + file offset), and the comment says which function passes it and how many entries it was called with. The collision
init is found as the function called most often with (task, table, count, mode) where the table is a literal. The entry layout was read from
its code (Physics/CollisionShape.h). A table address is a literal in two renderings of the pseudocode, &DAT_<address> and 0x<address>; calls
that take the table from a variable or a struct field are not found. A table is skipped if it is in no data section, or if an entry is not
plausible (a non-finite or huge float, a form above 10); the skipped ones are counted in the header's last comment. When two calls name the
same table with different counts, the largest count is used.
"""
import bisect, collections, math, os, re, struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) + "/"
DECOMP = ROOT + "sadxDecomp/"
PSEUDOCODE = DECOMP + "decompiled/pseudocode.c"
IMAGE = DECOMP + "rel/_Main.img"
LAYOUT = DECOMP + "rel/_Main.layout"
OUT = ROOT + "src/SAShapeKeys.h"
MODULE = "_Main.rel"
BASE = 0x80400000
ENTRY = 0x30
MAX_FORM = 10


def plausible(b, o):
    if o + ENTRY > len(b) or b[o + 1] > MAX_FORM:
        return False
    for off in (8, 12, 16, 0x14, 0x18, 0x1C):
        v = struct.unpack_from(">f", b, o + off)[0]
        if not math.isfinite(v) or abs(v) > 100000:
            return False
    return True


def main():
    img = open(IMAGE, "rb").read()
    sections = []
    for line in open(LAYOUT):
        t = line.split()
        if t[0].startswith("sec") and t[4] == "0" and int(t[2], 0) != 0:
            sections.append((int(t[1], 0), int(t[3], 0)))

    starts, names = [], []
    text = open(PSEUDOCODE, errors="replace").read()
    for m in re.finditer(r"^// FUN ([0-9a-f]{8}) (\S+)", text, re.M):
        starts.append(m.start())
        names.append("FUN_" + m.group(1))

    call = re.compile(r"\b(FUN_[0-9a-f]{8})\((\w+(?: \+ \w+)?),\s*(?:&DAT_|0x)([0-9a-f]{8}),\s*(\d+|0x[0-9a-f]+),\s*(\d+|0x[0-9a-f]+)\)")
    counts = collections.Counter(m.group(1) for m in call.finditer(text))
    init = counts.most_common(1)[0][0]

    tables = {}
    for m in call.finditer(text):
        if m.group(1) != init:
            continue
        addr = int(m.group(3), 16)
        fn = names[bisect.bisect_right(starts, m.start()) - 1]
        count = int(m.group(4), 0)
        cur = tables.setdefault(addr, [0, set()])
        cur[0] = max(cur[0], count)
        cur[1].add(fn)

    rows = []
    skipped = collections.Counter()
    for addr, (count, fns) in sorted(tables.items()):
        if not any(a <= addr < a + s for a, s in sections):
            skipped["in no data section"] += 1
            continue
        off = addr - BASE
        if not all(plausible(img, off + i * ENTRY) for i in range(count)):
            skipped["implausible entries"] += 1
            continue
        rows.append((off, count, addr, sorted(fns)))

    out = []
    out.append("#pragma once")
    out.append('#include "SAKeys.h"')
    out.append("")
    out.append("/*")
    out.append("GENERATED by tools/genSAShapeKeys.py, do not edit by hand (run the script again). One SACollisionShapesKey for each SADX object")
    out.append("collision table of _Main.rel passed to the game's collision init by a literal address (see the script for how, and for what is hypothesis).")
    out.append("Named SAShapes_Main_<RAM address>; the comment gives the entry count and the functions of sadxDecomp that pass the table")
    out.append("(FUN_<RAM address>). Which object a table belongs to is mostly not known (Sonic's is 0x354E10 of _Main.rel, see docs/ARCHITECTURE.md).")
    out.append("*/")
    for off, count, addr, fns in rows:
        out.append("/* %d entries, %s */" % (count, ", ".join(fns)))
        out.append('inline const SACollisionShapesKey SAShapes_Main_%08X{"%s", 0x%X, %d};' % (addr, MODULE, off, count))
    out.append("")
    out.append("/* %d tables; skipped: %s. */" % (len(rows), ", ".join("%d %s" % (v, k) for k, v in skipped.items()) or "none"))
    open(OUT, "w").write("\n".join(out) + "\n")
    print("init", init, "tables", len(rows), "skipped", dict(skipped))


main()
